// The smallest byte sequence the share-image check reads as a JPEG of the
// given size: SOI, an APP0 segment to step over, a baseline SOF0, EOI.
export function jpegBytes(width, height) {
  const app0 = [0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00];
  const sof0 = [0xFF, 0xC0, 0x00, 0x11, 0x08, height >> 8, height & 0xFF, width >> 8, width & 0xFF, 0x03, 0x01, 0x22, 0x00, 0x02, 0x11, 0x01, 0x03, 0x11, 0x01];
  return new Uint8Array([0xFF, 0xD8, ...app0, ...sof0, 0xFF, 0xD9]);
}

export function jpegFile(width, height, name = 'share.jpg') {
  return new File([jpegBytes(width, height)], name, { type: 'image/jpeg' });
}
